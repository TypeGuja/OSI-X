//! Диагностическое логирование паники.
//!
//! Профиль сборки использует `panic = "abort"` (см. `Cargo.toml`) — после
//! срабатывания паники контроллер перезагружается через встроенный
//! обработчик `esp-idf-sys`. Этот модуль не отменяет и не заменяет этот
//! механизм (что было бы небезопасно — прошивка станка с горячим соплом не
//! должна продолжать работу после паники), а лишь устанавливает
//! дополнительный обработчик, вызываемый непосредственно перед аварийным
//! завершением, чтобы записать причину в лог до перезагрузки. Не требует
//! `unsafe` — используется обычный `std::panic::set_hook`.

/// Устанавливает диагностический обработчик паники.
///
/// Должен вызываться один раз, как можно раньше в `main`, после
/// инициализации логирования (см. `logger::init`) — иначе сообщение о
/// панике будет потеряно, а не записано в лог перед перезагрузкой.
pub fn install_panic_hook() {
    std::panic::set_hook(Box::new(|info| {
        let location = info
            .location()
            .map(|l| format!("{}:{}:{}", l.file(), l.line(), l.column()))
            .unwrap_or_else(|| "неизвестное расположение".to_string());

        let message = info
            .payload()
            .downcast_ref::<&str>()
            .copied()
            .or_else(|| info.payload().downcast_ref::<String>().map(String::as_str))
            .unwrap_or("паника без текстового сообщения");

        log::error!("!!! ПАНИКА в {location}: {message}");
        log::error!("!!! станок будет перезагружен встроенным обработчиком паники ESP-IDF");
    }));
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn install_panic_hook_does_not_panic_itself() {
        // Сама установка хука не должна ничего ломать. Полноценный прогон
        // реальной паники намеренно не тестируется: профиль сборки
        // прошивки использует `panic = "abort"` (обязательно для
        // встраиваемой цели), при котором `std::panic::catch_unwind` не
        // перехватывает панику, а завершает процесс — включая процесс
        // `cargo test`. Это осознанное ограничение теста, вытекающее из
        // требований embedded-профиля, а не пропуск проверки поведения.
        install_panic_hook();
    }
}
